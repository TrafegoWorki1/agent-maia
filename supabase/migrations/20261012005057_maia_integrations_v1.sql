-- maia_integrations_v1
-- O que muda e por quê: catálogo de integrações por endpoint (API com URL, método e corpo), controlado pelo owner.
-- A Maia lista, propõe (sempre como pendente) e chama só o que está ativo; ativar exige aprovação do owner.
-- Segredos NUNCA entram aqui: secret_ref guarda só o NOME da variável de ambiente do servidor (prefixo INTEGRACAO_,
-- ou a chave da Evolution já existente). Nada além de adicionar: compatível com o código antigo.
-- Código que depende desta migração: server/integrations.ts, server/maiaImageTool.ts, server/codexMaiaMcp.ts,
-- server/access.ts, server/approvalPolicy.ts.
-- Rollback (nova migração que desfaz, nunca edição desta): desativar o recurso no código e, em migração posterior,
-- remover a permissão integracao.usar e a tabela maia_integrations.

insert into public.permission_catalog (code, label, description) values
  ('integracao.usar', 'Usar integrações', 'Pedir à Maia que use as integrações ativas do catálogo (reação no WhatsApp e outras que o owner ativar).')
on conflict (code) do nothing;

create table public.maia_integrations (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z][a-z0-9_]{2,40}$'),
  title text not null check (char_length(btrim(title)) between 1 and 80),
  description text not null check (char_length(btrim(description)) between 1 and 400),
  method text not null check (method in ('GET', 'POST', 'PUT', 'PATCH', 'DELETE')),
  url_template text not null check (char_length(url_template) between 10 and 400),
  body_template jsonb,
  auth_style text not null default 'nenhum' check (auth_style in ('nenhum', 'apikey_header', 'bearer')),
  auth_header text check (auth_header is null or auth_header ~ '^[A-Za-z][A-Za-z0-9-]{0,40}$'),
  secret_ref text check (secret_ref is null or secret_ref ~ '^[A-Z][A-Z0-9_]{2,60}$'),
  risk text not null default 'interna' check (risk in ('leitura', 'interna')),
  status text not null default 'pending' check (status in ('pending', 'active', 'paused')),
  required_permission text references public.permission_catalog(code),
  created_by text not null default 'maia',
  created_at timestamptz not null default now(),
  activated_at timestamptz,
  constraint maia_integrations_auth_consistent check (
    (auth_style = 'nenhum' and secret_ref is null)
    or (auth_style <> 'nenhum' and secret_ref is not null)
  )
);

create index maia_integrations_status_idx on public.maia_integrations (status);

alter table public.maia_integrations enable row level security;
revoke all on public.maia_integrations from public, anon, authenticated;
grant select, insert, update on public.maia_integrations to service_role;
grant usage, select on sequence public.maia_integrations_id_seq to service_role;

