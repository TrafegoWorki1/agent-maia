-- maia_prospeccao_v1
-- O que muda e por quê: tabelas da prospecção pedida pelo dono (Fase 4, 12/10/2026): lotes de contatos com uma mensagem
-- final, a lista de envios por contato (pendente, enviado, falhou ou pulado) e a lista de descadastro (quem pediu para sair).
-- Cada envio é uma ação com OK do dono (server/prospeccao.ts; ferramenta prospeccao_enviar_proximo). Teto diário de 30 envios
-- e nenhum contato repetido em 30 dias são aplicados pelo código antes de cada envio.
-- Código que depende desta migração: server/prospeccao.ts, server/maiaImageTool.ts, server/codexMaiaMcp.ts.
-- Rollback (nova migração que desfaz, nunca edição desta): desativar as ferramentas no código e, depois, remover as tabelas.
-- Só adiciona tabelas: compatível com o código antigo. RLS ligada e acesso só pelo servidor (service_role).

create table public.maia_prospect_batches (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 80),
  text text not null check (char_length(btrim(text)) between 1 and 2000),
  created_at timestamptz not null default now()
);

create table public.maia_prospects (
  id bigint generated by default as identity primary key,
  batch_id bigint not null references public.maia_prospect_batches(id) on delete cascade,
  number text not null check (number ~ '^[0-9]{12,13}$'),
  name text not null default '' check (char_length(name) <= 80),
  status text not null default 'pending' check (status in ('pending', 'sent', 'failed', 'skipped')),
  note text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  unique (batch_id, number)
);
create index maia_prospects_batch_status_idx on public.maia_prospects (batch_id, status);
create index maia_prospects_sent_at_idx on public.maia_prospects (sent_at) where status = 'sent';
create index maia_prospects_number_idx on public.maia_prospects (number, status);

create table public.maia_optouts (
  number text primary key check (number ~ '^[0-9]{12,13}$'),
  created_at timestamptz not null default now()
);

alter table public.maia_prospect_batches enable row level security;
alter table public.maia_prospects enable row level security;
alter table public.maia_optouts enable row level security;

revoke all on public.maia_prospect_batches, public.maia_prospects, public.maia_optouts from public, anon, authenticated;
grant select, insert, update, delete on public.maia_prospect_batches, public.maia_prospects, public.maia_optouts to service_role;
grant usage, select on sequence public.maia_prospect_batches_id_seq, public.maia_prospects_id_seq to service_role;
